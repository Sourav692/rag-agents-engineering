"""Export the course as the forwarddeployedprep.com AI Engineering curriculum (integration plan DATA-01).

    uv run python scripts/export_site_curriculum.py --out <site repo>/site/src/lib/rag-tracks.ts

Writes RAG_TRACKS, RAG_MODULES and RAG_LESSONS, typed for the site's curriculum.ts, from
- curriculum.yaml (parts, modules, lessons, notebooks),
- docs/fde-site-slugs.yaml (the frozen ids) and docs/fde-site-copy.yaml (track copy),
- theory/ (which lessons have a page, labs, reading length, the first interview question).

Each part is one track with one section; each module's lessons are its Overview, its lesson
pages in order and its Interview questions, with `source` set to the copy that
site/scripts/rag-theory-import.mjs vendors. Lessons without a page are `notebookOnly` items.
The field-by-field mapping is UX-03 in the integration plan. Same input, same bytes.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from curriculum_lib import ROOT, lesson_folder, load, module_dir, theory_dir  # noqa: E402

GH = "https://github.com/Sourav692/rag-agents-engineering/blob/main/"
VENDORED = "01_Concept_Tutorials/RAG_Agents_Engineering"
WPM = 180  # the site's reading speed
LAB_MINUTES = 20  # plan assumption A9
OPTIONAL_PARTS = {"graph", "capstone"}  # Parts XII and XIII (plan 4.1)
FIRST_PREREQUISITE = "orientation"  # the site's T0, which every track starts from
HEADER = """\
// Generated by rag-agents-engineering/scripts/export_site_curriculum.py from curriculum.yaml,
// docs/fde-site-slugs.yaml, docs/fde-site-copy.yaml and theory/. Do not edit: change those
// in the course repository and re-export.
import type { CurriculumLesson, CurriculumModule, CurriculumTrack } from './curriculum-types.ts'
"""


# British spelling, as site/src/lib/spelling.ts (the source of truth) defines it; the site's
# check:content fails on any word this misses.
AMERICAN = re.compile(
    r"^(?:un|re|pre|de|mis)?(?:behaviors?|behavioral(?:ly)?|authoriz(?:e|es|ed|ing|ation|ations|er|ers)"
    r"|optimiz(?:e|es|ed|ing|ation|ations|er|ers)|organiz(?:e|es|ed|ing|ation|ations|ational|er|ers)|judgments?"
    r"|(?:normaliz|summariz|paralleliz|prioritiz|recogniz|utiliz|minimiz|maximiz|categoriz|standardiz|emphasiz|realiz"
    r"|specializ|generaliz|finaliz|visualiz|customiz|memoriz|characteriz|centraliz|decentraliz|serializ|synchroniz"
    r"|operationaliz|apologiz|criticiz|analyz|paralyz|catalyz)(?:e|es|ed|ing|ation|ations|er|ers|able)"
    r"|(?:label|cancel|model|travel|signal|fuel|channel|level|total)(?:ed|ing|er|ers)"
    r"|centers?|centered|centering)$", re.I)
SPELLING_ALLOWED = [r"evaluator[-–]optimizer", r"\bParallelization\b", r"\bauthorizer\b"]


def british_word(word: str) -> str:
    if not AMERICAN.match(word):
        return word
    b = word.lower().replace("behavior", "behaviour").replace("judgment", "judgement")
    b = re.sub(r"([iy])z(e|es|ed|ing|ation|ations|ational|er|ers|able)$", r"\1s\2", b)
    b = re.sub(r"(label|cancel|model|travel|signal|fuel|channel|level|total)(ed|ing|er|ers)$", r"\1l\2", b)
    b = re.sub(r"center(s?)$", r"centre\1", b)
    b = re.sub(r"center(ed|ing)$", r"centr\1", b)
    return b.upper() if word.isupper() else b[0].upper() + b[1:] if word[0].isupper() else b


def british(text: str) -> str:
    """British spelling outside inline code, allowed names, paths and identifiers."""
    def prose(part: str) -> str:
        kept: list[str] = []
        for pat in SPELLING_ALLOWED:
            part = re.sub(pat, lambda m: f"\0{kept.append(m.group(0)) or len(kept) - 1}\0", part)
        part = re.sub(r"\S+", lambda m: m.group(0) if re.search(r"[_/\\]", m.group(0))
                      else re.sub(r"[A-Za-z]+", lambda w: british_word(w.group(0)), m.group(0)), part)
        return re.sub(r"\0(\d+)\0", lambda m: kept[int(m.group(1))], part)
    return "".join(p if i % 2 else prose(p) for i, p in enumerate(re.split(r"(`[^`]*`)", text)))


def words(text: str) -> int:
    return len(re.sub(r"```.*?```", " ", text, flags=re.S).split())


def first_question(readme: str) -> str:
    q = re.search(r"^## Interview Spotlight.*?^### 1\. ([^\n]+)$", readme, flags=re.M | re.S)
    if not q:
        raise ValueError("no first interview question")
    return british(q.group(1).strip())


def module_entry(m: dict, code: str, track: dict, ids: dict) -> tuple[dict, list[dict]]:
    tdir = ROOT / theory_dir(m)
    readme = (tdir / "README.md").read_text()
    vendored = f"{VENDORED}/{theory_dir(m).split('/', 1)[1]}"
    lessons = [{"slug": ids["overview"], "title": "Overview", "source": f"{vendored}/00_overview.md"}]
    notebook_only = []
    minutes, labs = words(readme) / WPM, 0
    for n, les in enumerate(m["lessons"], 1):
        folder = lesson_folder(n, les["title"])
        page = tdir / folder / "README.md"
        if page.exists():
            lab_count = len(list((tdir / folder / "interactive").glob("*.html")))
            minutes += words(page.read_text()) / WPM + LAB_MINUTES * lab_count
            labs += lab_count
            lessons.append({"slug": ids["lessons"][les["title"]], "title": british(les["title"]),
                            "source": f"{vendored}/{folder}.md"})
        else:
            notebook_only.append({"title": british(les["title"]), "notebooks": [
                {"title": it["file"], "href": f"{GH}{module_dir(m)}/{it['folder']}/{it['file']}",
                 "optional": it["tier"] != "mandatory"}
                for it in les["items"]]})
    lessons.append({"slug": ids["interview"], "title": "Interview questions",
                    "source": f"{vendored}/99_interview_questions.md"})
    notebook_hours = max(0.0, round((m["hours"] * 60 - minutes) / 30) / 2)
    scope = f"Course module M{m['num']:02d}."
    if notebook_hours:
        scope += f" Plus about {notebook_hours:g} h of notebook work on GitHub."
    module = {
        "slug": ids["slug"], "code": code, "title": british(m["title"]),
        "track": track["slug"], "section": track["section"],
        "status": "ready", **({"practiceMinutes": LAB_MINUTES} if labs else {}),
        "objective": british(m["objectives"][0]), "scope": scope, "prerequisites": [], "deliverable": british(m["lab"]),
        "assessment": "Answer the five Interview questions without notes" + (", then run the lab." if labs else "."),
        "interviewProbe": first_question(readme), "commonMistakes": [],
        "lessons": [les["slug"] for les in lessons], "seeAlso": [],
        **({"notebookOnly": notebook_only} if notebook_only else {}),
    }
    home = [{**les, "home": ids["slug"], "kind": "sync", "publish": "own"} for les in lessons]
    return module, home


def export() -> str:
    cur = load()
    slugs = yaml.safe_load((ROOT / "docs/fde-site-slugs.yaml").read_text())
    copy = yaml.safe_load((ROOT / "docs/fde-site-copy.yaml").read_text())
    tracks, modules, lessons = [], [], []
    prerequisite = FIRST_PREREQUISITE
    for p in cur["parts"]:
        t, c = slugs["tracks"][p["id"]], copy[p["id"]]
        mods = [m for m in cur["modules"] if m["part"] == p["id"] and (ROOT / theory_dir(m) / "README.md").exists()]
        for i, m in enumerate(mods, 1):
            module, home = module_entry(m, f"{t['code']}.{i}", t, slugs["modules"][m["key"]])
            modules.append(module)
            lessons += home
        tracks.append({
            "slug": t["slug"], "code": t["code"], "title": british(p["title"]), "objective": british(p["summary"]),
            "forWhom": c["forWhom"],
            "prerequisites": [prerequisite], "required": "no" if p["id"] in OPTIONAL_PARTS else "yes",
            "exitCompetencies": c["exitCompetencies"],
            "sections": [{
                "slug": t["section"], "title": british(p["title"]),
                "whyItMatters": c["whyItMatters"], "outcomes": c["outcomes"],
                "exercise": c["exercise"], "assessment": "Each module's Interview questions",
                "interviewRelevance": c["interviewRelevance"],
                "doneWhen": "You can answer every module's Interview questions without notes",
                "modules": [m["slug"] for m in modules if m["track"] == t["slug"]],
            }],
        })
        prerequisite = t["slug"]

    def ts(name: str, kind: str, rows: list) -> str:
        return f"\nexport const {name}: {kind}[] = {json.dumps(rows, indent=2, ensure_ascii=False)}\n"

    return HEADER + ts("RAG_TRACKS", "CurriculumTrack", tracks) + ts("RAG_MODULES", "CurriculumModule", modules) \
        + ts("RAG_LESSONS", "CurriculumLesson", lessons)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True, help="the site's src/lib/rag-tracks.ts")
    out = ap.parse_args().out
    out.write_text(export())
    print(f"site curriculum: wrote {out}")
