def write(path, text):
    (ROOT / path).write_text(text.rstrip("\n") + "\n", encoding="utf-8")


def mref(num):
    return f"M{num:02d}"


def mod_span(keys):
    """Module keys -> 'M09–M10' for a consecutive run, else 'M30, M32'."""
    nums = sorted(MOD_BY_KEY[k]["num"] for k in keys)
    if len(nums) > 1 and nums == list(range(nums[0], nums[-1] + 1)):
        return f"{mref(nums[0])}–{mref(nums[-1])}"
    return ", ".join(mref(n) for n in nums)


def src_url(it):
    return f"{GH}/{SOURCES[it.repo]['repo']}/blob/main/{it.source_path}"


