def coverage():
    data = yaml.safe_load((ROOT / "docs/agentic-architectures.yaml").read_text())
    up = data["upstream"]
    fams = data["families"]
    arch = data["architectures"]
    for a in arch:
        missing = [s for s in a["notebooks"] if s not in BY_SRC]
        if missing:
            raise SystemExit(f"docs/agentic-architectures.yaml #{a['num']}: not placed in curriculum.yaml: {missing}")
        a["items"] = [BY_SRC[s] for s in a["notebooks"]]
        a["mandatory"] = any(not it.optional for it in a["items"])
        a["mods"] = ", ".join(sorted({mref(it.module["num"]) for it in a["items"]}))
    if {a["family"] for a in arch} != set(fams):
        raise SystemExit("docs/agentic-architectures.yaml: families list does not match the architectures")
    n = len(arch)
    counts = {s: sum(a["status"] == s for a in arch) for s in STATUS}
    mand = [a for a in arch if a["mandatory"]]
    opt_only = [a for a in arch if not a["mandatory"]]
    repos = sorted({it.repo for a in arch for it in a["items"]})
    repos_txt = ", ".join(repos[:-1]) + f" and {repos[-1]}"
    opt_list = ", ".join(f"#{a['num']} {a['name']}" for a in opt_only)
    merged = next(a["name"] for a in arch if a["status"] == "merged")
    adapted = next(a["name"] for a in arch if a["status"] == "adapted")

    def label(it):
        return f"{mref(it.module['num'])}/{it.folder}/{it.file.removesuffix('.ipynb')}"

    # Markdown: links relative to docs/
    L = ["# Agentic Architecture Coverage", "", GEN_NOTE.format(extra=" and `docs/agentic-architectures.yaml`"),
         f"Comparison of [all-agentic-architectures]({up}) ({n} architectures) with this course "
         f"({len(MODULES)} modules, {len(SOURCES)} source repos). The architectures are taught by notebooks from repos {repos_txt}; "
         "paths and module numbers below are the course's (`course/<part>/<module>/<folder>/<file>`).", "",
         "## Verdict", "",
         f"**All {n} architectures are covered.** {counts['full']} have a dedicated notebook, {counts['merged']} is merged into "
         f"another notebook ({merged}), and {counts['adapted']} is taught as an adaptation ({adapted}).", "",
         f"**{len(mand)} are on the mandatory track; {len(opt_only)} are taught only in optional notebooks** "
         f"({opt_list}). Optional notebooks are marked *(optional)* in the table.", "",
         "| Family | Architectures | On mandatory track |", "|---|---|---|"]
    for f in fams:
        fa = [a for a in arch if a["family"] == f]
        L.append(f"| {f} | {len(fa)}/{len(fa)} covered | {sum(a['mandatory'] for a in fa)} |")
    L += ["", "## Architecture-by-architecture mapping", "",
          "| # | Architecture | Family | Status | Course notebook(s) | Source | Module |", "|---|---|---|---|---|---|---|"]
    for a in arch:
        nbs = "<br>".join(f"[`{label(it)}`](../{it.dest})" + (" *(optional)*" if it.optional else "") for it in a["items"])
        srcs = "<br>".join(f"[{it.repo}]({src_url(it)})" for it in a["items"])
        L.append(f"| {a['num']} | [{a['name']}]({up}/blob/main/notebooks/{a['upstream']}.ipynb) | {a['family']} | "
                 f"{STATUS[a['status']]} | {nbs} | {srcs} | {a['mods']} |")
    notes = [a for a in arch if a.get("note")]
    if notes:
        L += ["", "### Notes on partial matches", ""] + [f"- **{a['name']} (#{a['num']}):** {a['note']}" for a in notes]
    L += ["", "## In the course but not in the upstream catalogue", "", "| Area | Patterns | Repo · module |", "|---|---|---|"]
    L += [f"| {c['area']} | {c['patterns']} | {c['repo']} · {mod_span(c['modules'])} |" for c in data["course_only"]]
    L += ["", "## In the upstream repo but not in the course", "", "These are engineering extras, not architectures:", ""]
    L += [f"- **{u['name']}:** {u['detail']}" for u in data["upstream_only"]]
    if data.get("housekeeping"):
        L += ["", "## Housekeeping", ""] + [f"- {h}" for h in data["housekeeping"]]
    write("docs/agentic-architecture-coverage.md", "\n".join(L))

    # HTML: links to GitHub, like docs/site/index.html
    H = ['<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">',
         "<title>Agentic Architecture Coverage</title>", FONTS, f"<style>{COV_CSS}</style></head><body><div class='wrap'>",
         "<header><p class='eyebrow'>all-agentic-architectures vs the RAG &amp; Agents Engineering course</p><h1>Agentic Architecture Coverage</h1>",
         f"<p class='lede'>Each of the {n} architectures in the <a href='{up}' target='_blank' rel='noopener'>upstream catalogue</a>, "
         f"matched to the course notebook that teaches it ({mref(1)}–{mref(len(MODULES))} numbering) and the source repo it is synced from. "
         "Generated from <code>curriculum.yaml</code> and <code>docs/agentic-architectures.yaml</code>.</p></header>",
         f"<section class='verdict'><div class='big'>{n}<small>/{n}</small></div><p><strong>Every architecture is covered.</strong> "
         f"{counts['full']} have a dedicated notebook; {E(merged)} is merged into another notebook and {E(adapted)} is taught as an adaptation. "
         f"{len(mand)} sit on the mandatory track; {len(opt_only)} are taught only in optional notebooks (filter below).</p></section>",
         "<section><h2>By family</h2><p class='muted' style='margin:0'>Select a family to filter the table.</p>"
         "<div class='fams' role='group' aria-label='Filter by family'>"]
    for f in fams:
        k = sum(a["family"] == f for a in arch)
        H.append(f"<button class='fam' data-fam='{E(f)}' aria-pressed='false'><b>{k}/{k}</b><span>{E(f)}</span></button>")
    H.append("</div><div class='bar' role='group' aria-label='Filter by status and track'><span class='muted'>Show:</span>"
             f"<button class='chip' data-st='all' aria-pressed='true'>All {n}</button>"
             f"<button class='chip' data-st='mand' aria-pressed='false'>On mandatory track ({len(mand)})</button>"
             f"<button class='chip' data-st='optonly' aria-pressed='false'>Optional only ({len(opt_only)})</button>")
    H += [f"<button class='chip' data-st='{s}' aria-pressed='false'>{lab} ({counts[s]})</button>" for s, lab in STATUS.items()]
    H.append("</div><div class='tbl'><table><thead><tr><th>#</th><th>Architecture</th><th>Family</th><th>Status</th>"
             "<th>Course notebook(s)</th><th>Module</th></tr></thead><tbody>")
    for a in arch:
        nbs = "".join(
            f"<a class='nb' href='{COURSE_URL}/blob/main/{it.dest}' target='_blank' rel='noopener' title='source: {E(src_url(it))}'>"
            f"<span class='repo r{it.repo}'>{it.repo}</span><span>{E(label(it))}</span>"
            f"{'<em class=opt>optional</em>' if it.optional else ''}</a>" for it in a["items"])
        nt = f"<div class='note'>{E(a['note'])}</div>" if a.get("note") else ""
        H.append(f"<tr data-fam='{E(a['family'])}' data-st='{a['status']}' data-tr='{'mand' if a['mandatory'] else 'optonly'}'>"
                 f"<td class='n'>{a['num']:02d}</td><td><a href='{up}/blob/main/notebooks/{a['upstream']}.ipynb' target='_blank' rel='noopener'>{E(a['name'])}</a></td>"
                 f"<td>{E(a['family'])}</td><td><span class='st st-{a['status']}'>{STATUS[a['status']]}</span></td><td>{nbs}{nt}</td><td class='n'>{a['mods']}</td></tr>")
    H.append("</tbody></table></div></section>")
    H.append("<section class='two'><div class='card'><h3>In the course, not in the catalogue</h3><div class='tbl' style='border:0'><table>"
             "<thead><tr><th>Area</th><th>Patterns</th><th>Where</th></tr></thead><tbody>")
    H += [f"<tr><td>{E(c['area'])}</td><td>{E(c['patterns'])}</td><td class='n'>{c['repo']} · {mod_span(c['modules'])}</td></tr>" for c in data["course_only"]]
    H.append("</tbody></table></div></div><div class='card'><h3>In the catalogue, not in the course</h3>"
             "<p class='muted' style='margin:0'>Engineering extras, not architectures.</p><ul>")
    H += [f"<li><strong>{E(u['name'])}.</strong> {E(u['detail'])}</li>" for u in data["upstream_only"]]
    H.append("</ul>")
    if data.get("housekeeping"):
        H.append("<h3>Housekeeping</h3>" + "".join(f"<p style='margin:0'>{E(h).replace('`', '')}</p>" for h in data["housekeeping"]))
    H.append(f"</div></section></div>{COV_JS}</body></html>")
    write("docs/site/agentic-architecture-coverage.html", "\n".join(H))
    return n, len(mand)


